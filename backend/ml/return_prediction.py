import json
import logging
from pathlib import Path
from typing import Dict, Any, List, Optional
import pandas as pd
try:
    from catboost import CatBoostClassifier
except ImportError:
    CatBoostClassifier = None

from backend.ml.features import prepare_prediction_dataset, extract_features_and_target, FORBIDDEN_LEAKAGE_COLUMNS
from backend.services.storage import storage_service

logger = logging.getLogger(__name__)

class ReturnPredictionService:
    """Production ML Return Prediction Service loading trained CatBoostClassifier model artifacts and running real inference."""

    MODEL_FILE = Path("models/return_prediction_model.cbm")
    METADATA_FILE = Path("models/return_prediction_metadata.json")

    _model: Optional[CatBoostClassifier] = None
    _metadata: Optional[Dict[str, Any]] = None

    @classmethod
    def is_prediction_query(cls, question: str) -> bool:
        q_lower = question.lower()
        return any(kw in q_lower for kw in ["predict", "likely to be returned", "probability of return", "risk of return", "return risk"])

    @classmethod
    def _load_artifacts(cls) -> bool:
        if cls._model is not None and cls._metadata is not None:
            return True

        if CatBoostClassifier is None or not cls.MODEL_FILE.exists() or not cls.METADATA_FILE.exists():
            return False

        try:
            cls._model = CatBoostClassifier()
            cls._model.load_model(str(cls.MODEL_FILE))

            with open(cls.METADATA_FILE, "r") as f:
                cls._metadata = json.load(f)
            return True
        except Exception as e:
            logger.error(f"Failed loading CatBoost return prediction model artifacts: {e}")
            return False

    @classmethod
    def predict_return_risk(cls, question: str, top_k: int = 10) -> Dict[str, Any]:
        if not cls._load_artifacts():
            return {
                "error": "Return prediction model has not been trained. Run scripts/train_return_model.py first.",
                "status": "MODEL_UNAVAILABLE"
            }

        # Load data tables from storage_service or data/
        try:
            data_dir = Path("data")
            orders_df = pd.read_csv(data_dir / "orders.csv")
            returns_df = pd.read_csv(data_dir / "returns.csv")
            customers_df = pd.read_csv(data_dir / "customers.csv")
            order_items_df = pd.read_csv(data_dir / "order_items.csv")
            products_df = pd.read_csv(data_dir / "products.csv")

            prepared_df = prepare_prediction_dataset(orders_df, returns_df, customers_df, order_items_df, products_df)
            X, _, feature_names, _ = extract_features_and_target(prepared_df, is_training=False)

            # Ensure model features match
            model_features = cls._metadata.get("feature_names", feature_names)
            X_eval = X[model_features]

            # Run real probability prediction
            probs = cls._model.predict_proba(X_eval)[:, 1]
            prepared_df["predicted_return_prob"] = probs

            # Rank top-k high risk orders
            top_df = prepared_df.sort_values(by="predicted_return_prob", ascending=False).head(top_k)

            predictions = []
            for _, row in top_df.iterrows():
                prob_val = float(round(row["predicted_return_prob"], 4))
                risk_lbl = "High" if prob_val >= 0.50 else ("Medium" if prob_val >= 0.25 else "Low")
                predictions.append({
                    "order_id": str(row["order_id"]),
                    "customer_id": str(row["customer_id"]),
                    "category": str(row.get("category", "N/A")),
                    "final_amount": float(row.get("final_amount", 0.0)),
                    "predicted_return_prob": prob_val,
                    "risk_level": risk_lbl
                })

            metrics = cls._metadata.get("metrics", {})
            return {
                "label": "MODEL PREDICTION",
                "model_metadata": cls._metadata,
                "predictions": predictions,
                "metrics": metrics,
                "disclaimer": f"This output was generated by CatBoost model inference (ROC-AUC: {metrics.get('roc_auc', 'N/A')}, F1: {metrics.get('f1_score', 'N/A')}). Predictive results are probabilistic models, not verified factual calculations."
            }

        except Exception as ex:
            logger.error(f"Inference error in ReturnPredictionService: {ex}")
            return {
                "error": f"Error executing return prediction inference: {str(ex)}",
                "status": "INFERENCE_FAILED"
            }
