def test_kaggle_missing_profit_refusal(kaggle_datasets):
    orchestrator = get_orchestrator()
    # Query requesting profit from orders table (which lacks net profit column)
    orders_only = [d for d in kaggle_datasets if "orders" in d and "items" not in d]
    req = AnalysisRequest(
        question="What is the net profit for Q3?",
        selected_datasets=orders_only
    )
    res = orchestrator.process_analysis(req)
    assert res.status == AnalysisStatus.REFUSED
    assert res.refusal_reason == "insufficient_data"

