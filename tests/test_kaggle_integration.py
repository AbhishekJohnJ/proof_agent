@pytest.fixture(scope="module")
def kaggle_datasets():
    return [d["dataset_id"] for d in dataset_catalog.list_datasets()]

def test_kaggle_dataset_manifest_exists():
    manifest_path = Path("data/dataset_manifest.json")
    assert manifest_path.exists(), "data/dataset_manifest.json should exist."
    with open(manifest_path, "r") as f:
        data = json.load(f)
    assert "datasets" in data
    assert "orders" in data["datasets"]
    assert "customers" in data["datasets"]
    assert len(data["relationships"]) > 0

def test_kaggle_total_revenue(kaggle_datasets):
    orchestrator = get_orchestrator()
    req = AnalysisRequest(
        question="What is the total revenue?",
        selected_datasets=kaggle_datasets
    )
    res = orchestrator.process_analysis(req)
    assert res.status == AnalysisStatus.VERIFIED
    assert res.canonical_result is not None
    assert res.canonical_result.result > 2.0e9  # Ground truth ~ 2.57B INR

