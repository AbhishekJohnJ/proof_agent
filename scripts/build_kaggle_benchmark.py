import json
import pandas as pd
from pathlib import Path

def generate_benchmark():
    data_dir = Path("data")
    
    customers_df = pd.read_csv(data_dir / "customers.csv")
    products_df = pd.read_csv(data_dir / "products.csv")
    orders_df = pd.read_csv(data_dir / "orders.csv")
    order_items_df = pd.read_csv(data_dir / "order_items.csv")
    returns_df = pd.read_csv(data_dir / "returns.csv")

    # 1. Total revenue (Sum of orders.final_amount)
    total_revenue = float(orders_df["final_amount"].sum())

    # 2. Average order value (Mean of orders.final_amount)
    aov = float(orders_df["final_amount"].mean())

    # 3. Category revenue (highest revenue product category from order_items joined with products)
    items_products = pd.merge(order_items_df, products_df, on="product_id")
    cat_rev = items_products.groupby("category")["item_revenue"].sum().reset_index()
    top_cat_row = cat_rev.sort_values(by="item_revenue", ascending=False).iloc[0]
    top_category = top_cat_row["category"]
    top_category_revenue = float(top_cat_row["item_revenue"])

    # 4. Premium customer revenue (orders final_amount for customers with customer_segment == 'Premium')
    cust_orders = pd.merge(orders_df, customers_df, on="customer_id")
    premium_orders = cust_orders[cust_orders["customer_segment"].str.lower() == "premium"]
    premium_revenue = float(premium_orders["final_amount"].sum())

    # 5. Highest sales state (state with highest sum of final_amount)
    state_sales = cust_orders.groupby("state")["final_amount"].sum().reset_index()
    top_state_row = state_sales.sort_values(by="final_amount", ascending=False).iloc[0]
    top_state = top_state_row["state"]
    top_state_sales = float(top_state_row["final_amount"])

    # 6. Overall return rate (% of total orders that exist in returns)
    total_orders_count = len(orders_df)
    returned_orders_count = orders_df["order_id"].isin(returns_df["order_id"]).sum()
    return_rate_pct = float(round((returned_orders_count / total_orders_count) * 100.0, 2))

    # 7. Customer segment with highest average order value
    seg_aov = cust_orders.groupby("customer_segment")["final_amount"].mean().reset_index()
    top_seg_row = seg_aov.sort_values(by="final_amount", ascending=False).iloc[0]
    top_segment = top_seg_row["customer_segment"]
    top_segment_aov = float(top_seg_row["final_amount"])

    # 8. Revenue generated by customers who returned products
    returning_cust_ids = returns_df["customer_id"].unique()
    returning_cust_orders = orders_df[orders_df["customer_id"].isin(returning_cust_ids)]
    returning_cust_revenue = float(returning_cust_orders["final_amount"].sum())

    # 9. Product category with highest return rate (% of category items returned)
    ret_items = pd.merge(returns_df, products_df, on="product_id")
    cat_returns_count = ret_items.groupby("category")["return_id"].count()
    cat_total_items = items_products.groupby("category")["order_item_id"].count()
    cat_return_rate = (cat_returns_count / cat_total_items * 100.0).reset_index(name="return_rate")
    top_ret_cat_row = cat_return_rate.sort_values(by="return_rate", ascending=False).iloc[0]
    top_return_category = top_ret_cat_row["category"]
    top_return_category_rate = float(round(top_ret_cat_row["return_rate"], 2))

    benchmark = {
        "dataset": "Indian E-Commerce Sales & Customer Analytics",
        "total_revenue": total_revenue,
        "average_order_value": round(aov, 2),
        "highest_revenue_category": {
            "category": top_category,
            "revenue": round(top_category_revenue, 2)
        },
        "premium_customer_revenue": round(premium_revenue, 2),
        "highest_sales_state": {
            "state": top_state,
            "sales": round(top_state_sales, 2)
        },
        "return_rate_percentage": return_rate_pct,
        "highest_aov_segment": {
            "segment": top_segment,
            "aov": round(top_segment_aov, 2)
        },
        "returning_customers_revenue": round(returning_cust_revenue, 2),
        "highest_return_rate_category": {
            "category": top_return_category,
            "return_rate": top_return_category_rate
        }
    }

    out_path = Path("tests/benchmark/kaggle_expected_results.json")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(benchmark, f, indent=2)

    print(f"Benchmark calculated and saved to {out_path}:")
    print(json.dumps(benchmark, indent=2))

if __name__ == "__main__":
    generate_benchmark()
